#!/usr/bin/env python3
"""Extract only the u8g2 font blobs TIXEL needs from the full u8g2_fonts.c.

The full table is ~40 MB; linking it would be absurd on an MCU. This keeps the
subset honest: byte-identical arrays, same order, no conversion.

    python tools/extract_fonts.py                     # default: ../u8g2-dl
    python tools/extract_fonts.py path/to/u8g2_fonts.c
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_CPP = os.path.join(ROOT, "components", "tixel", "src", "fonts_data.cpp")
OUT_HPP = os.path.join(ROOT, "components", "tixel", "include", "tixel", "fonts.hpp")

# symbol -> (u8g2 font name, role comment)
FONTS = [
    ("font_ui",        "u8g2_font_wqy12_t_gb2312", "body text, CJK + latin"),
    ("font_mid",       "u8g2_font_logisoso28_tr",  "values, percentages"),
    ("font_big",       "u8g2_font_logisoso42_tn",  "clock digits"),
    ("font_logo",      "u8g2_font_logisoso34_tr",  "wordmark"),
    # 128x64 reference set: same fonts as the reference geometry
    ("font_ui_64",     "u8g2_font_haxrcorp4089_tr", "upstream body text"),
    ("font_tiny_64",   "u8g2_font_4x6_tr",          "upstream status text"),
    ("font_mid_64",    "u8g2_font_logisoso16_tr",   "upstream values"),
    ("font_big_64",    "u8g2_font_logisoso28_tn",   "upstream clock digits"),
    ("font_logo_64",   "u8g2_font_logisoso22_tr",   "upstream wordmark"),
]

ESC = {"n": 10, "t": 9, "r": 13, "\\": 92, '"': 34, "'": 39, "0": 0}


def decode_c_string(blob: str) -> bytes:
    """Decode the octal-escaped literals u8g2_fonts.c uses."""
    out = bytearray()
    i = 0
    n = len(blob)
    while i < n:
        c = blob[i]
        if c != "\\":
            out.append(ord(c))
            i += 1
            continue
        i += 1
        c = blob[i]
        if c.isdigit():
            j = i
            while j < n and j < i + 3 and blob[j].isdigit():
                j += 1
            out.append(int(blob[i:j], 8) & 0xFF)
            i = j
        else:
            out.append(ESC.get(c, ord(c)))
            i += 1
    return bytes(out)


def find_font(src: str, name: str):
    pat = re.compile(r"const\s+uint8_t\s+" + name + r"\s*\[[^\]]*\]\s*U8G2_FONT_SECTION\([^)]*\)\s*=\s*")
    m = pat.search(src)
    if not m:
        raise SystemExit("font not found: " + name)
    # the body is one or more adjacent string literals, wrapped across lines
    i = m.end()
    chunks = []
    while True:
        while src[i] in " \t\r\n":
            i += 1
        if src[i] == ";":
            break
        if src[i] != '"':
            raise SystemExit("unexpected font body for " + name)
        i += 1
        start = i
        while src[i] != '"':
            i += 2 if src[i] == "\\" else 1
        chunks.append(src[start:i])
        i += 1
    return decode_c_string("".join(chunks))


def escaped(data: bytes, per_line: int = 24) -> str:
    parts = []
    for b in data:
        parts.append("\\%o" % b if b < 0x80 else "\\%o" % b)
    lines = []
    for i in range(0, len(parts), per_line):
        lines.append('  "' + "".join(parts[i:i + per_line]) + '"')
    return "\n".join(lines)


def main():
    src_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.dirname(ROOT)), "ESP-IDF", "u8g2-dl", "csrc", "u8g2_fonts.c")
    if not os.path.exists(src_path):
        raise SystemExit("u8g2_fonts.c not found: " + src_path)
    with open(src_path, "r", encoding="utf-8", errors="replace") as f:
        src = f.read()

    rows = []
    for sym, u8name, role in FONTS:
        data = find_font(src, u8name)
        glyph_cnt = data[0]
        ascent, descent = data[13], data[14]
        rows.append((sym, u8name, role, data, glyph_cnt, ascent, descent))
        print("%-14s %-28s %5d B  %3d glyphs  ascent %2d descent %2d" %
              (sym, u8name, len(data), glyph_cnt, ascent, descent))

    with open(OUT_CPP, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/extract_fonts.py from the u8g2 font library.\n")
        f.write("// Byte-identical u8g2 font blobs; do not edit by hand.\n")
        f.write('#include "tixel/fonts.hpp"\n\n')
        f.write("namespace tixel {\nnamespace fonts {\n\n")
        for sym, u8name, role, data, cnt, asc, desc in rows:
            f.write("// %s - %s (ascent %d, descent %d)\n" % (u8name, role, asc, desc))
            f.write("const uint8_t %s[] =\n%s;\n\n" % (sym, escaped(data)))
        f.write("}  // namespace fonts\n}  // namespace tixel\n")

    os.makedirs(os.path.dirname(OUT_HPP), exist_ok=True)
    with open(OUT_HPP, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/extract_fonts.py; names are stable API.\n")
        f.write("#pragma once\n\n#include <cstdint>\n\nnamespace tixel {\nnamespace fonts {\n\n")
        for sym, u8name, role, data, cnt, asc, desc in rows:
            f.write("extern const uint8_t %s[];  // %s\n" % (sym, u8name))
        f.write("\n}  // namespace fonts\n}  // namespace tixel\n")

    print("\nwrote", OUT_CPP)
    print("wrote", OUT_HPP)


if __name__ == "__main__":
    main()
